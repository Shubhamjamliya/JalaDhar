export const getStatesList = (query = '') => {
  const states = Object.keys(INDIAN_STATES_DISTRICTS);
  if (!query) return states;
  const q = query.toLowerCase().trim();
  return states.filter(s => s.toLowerCase().includes(q));
};

export const getDistrictsList = (state = '', query = '') => {
  let districts = [];
  if (state && INDIAN_STATES_DISTRICTS[state]) {
    districts = INDIAN_STATES_DISTRICTS[state];
  } else {
    // If state is not selected or invalid, combine all districts
    Object.values(INDIAN_STATES_DISTRICTS).forEach(list => {
      districts.push(...list);
    });
    districts = Array.from(new Set(districts));
  }

  if (!query) return districts;
  const q = query.toLowerCase().trim();
  return districts.filter(d => d.toLowerCase().includes(q));
};

export const findStateForDistrict = (districtName) => {
  if (!districtName) return null;
  const target = districtName.toLowerCase().trim();
  for (const [state, districts] of Object.entries(INDIAN_STATES_DISTRICTS)) {
    if (districts.some(d => d.toLowerCase() === target)) {
      return state;
    }
  }
  return null;
};
